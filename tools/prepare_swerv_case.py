"""Materialize public PDK and authorized shared netlist; never read private PDK paths."""
from pathlib import Path
import base64,hashlib,json,subprocess,urllib.request

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'runs/medium-macro-fullflow-20261114'
CASE=ROOT/'cases/ibench/swerv_nangate45'

def main():
    source=json.loads((OUT/'public-pdk-source.json').read_text())
    records=[]
    for path in source['paths']:
        if path.endswith(('macro.lef','macro.rect.lef')):continue
        rel='pdk/'+path.split('/nangate45/',1)[1]
        dest=CASE/rel;dest.parent.mkdir(parents=True,exist_ok=True)
        url='https://raw.githubusercontent.com/The-OpenROAD-Project/OpenROAD-flow-scripts/'+source['commit']+'/'+path
        if not dest.exists():
            api='https://api.github.com/repos/The-OpenROAD-Project/OpenROAD-flow-scripts/contents/'+path+'?ref='+source['commit']
            with urllib.request.urlopen(api,timeout=60) as r:payload=json.load(r)
            if payload.get('encoding')!='base64':
                with urllib.request.urlopen(payload['git_url'],timeout=60) as r:payload=json.load(r)
            if payload.get('encoding')!='base64':raise ValueError('Expected GitHub blob: '+path)
            dest.write_bytes(base64.b64decode(payload['content']))
        records.append({'relative':rel,'source':url,'sha256':hashlib.sha256(dest.read_bytes()).hexdigest()})
    code='''
from pathlib import Path
import json,base64
p=Path('/srv/benchmarks/iBench/benchmarks/designs/swerv_wrapper')
mapping={'netlist/design.v':'synthesis_2d/native_structural/native.v','sdc/design.sdc':'sdc/swerv_wrapper.sdc','provenance/source-design.json':'design.json','provenance/normalization.json':'synthesis_2d/native_structural/normalization.json','provenance/original.v':'netlist/swerv_wrapper.v'}
print(json.dumps({k:{'data':base64.b64encode((p/v).read_bytes()).decode(),'source':str(p/v)} for k,v in mapping.items()}))
'''
    r=subprocess.run(['ssh','-o','BatchMode=yes','-o','ConnectTimeout=15','eda-worker','python3 -B -'],input=code,text=True,capture_output=True,timeout=60)
    if r.returncode:raise RuntimeError(r.stderr)
    for rel,value in json.loads(r.stdout).items():
        p=CASE/rel;p.parent.mkdir(parents=True,exist_ok=True);p.write_bytes(base64.b64decode(value['data']))
        records.append({'relative':rel,'source':value['source'],'sha256':hashlib.sha256(p.read_bytes()).hexdigest()})
    audit=json.loads((OUT/'swerv-input-audit.json').read_text())
    for old,cfg in audit['config'].items():
        name={'pl.json':'pl_default_config.json','cts.json':'cts_default_config.json','db.json':'db_default_config.json','flow.json':'flow_config.json'}[old]
        # Relocate only metadata paths; scripts are generated by the registered adapter.
        text=json.dumps(cfg,indent=2).replace('/srv/benchmarks/iBench/benchmarks/results/full_2d_20261021/swerv_wrapper','/work')
        for a,b in [('pl.json','pl_default_config.json'),('cts.json','cts_default_config.json'),('db.json','db_default_config.json')]:text=text.replace(a,b)
        p=CASE/'config'/name;p.parent.mkdir(exist_ok=True);p.write_text(text,encoding='utf-8')
    (CASE/'provenance/sources.json').write_text(json.dumps(records,indent=2),encoding='utf-8')
    hist=json.loads((OUT/'historical-baselines.json').read_text())['swerv_wrapper']['report/baseline/run.json']['input_sha256']
    for r in records:
        expected=next((h for n,h in hist.items() if Path(n).name==Path(r['relative']).name),None)
        print(r['relative'],r['sha256'],'historical_match',r['sha256']==expected if expected else None)

if __name__=='__main__':main()
